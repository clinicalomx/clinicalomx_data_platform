"""Generate `src/clinicalomx_omop/cdm/v<version>.py` from the vendored OHDSI specification.

    uv run python scripts/generate_cdm.py           # write the module
    uv run python scripts/generate_cdm.py --check   # exit 1 if the committed module is stale

Everything comes from the OHDSI CSVs in `spec/source.toml`, whose sha256 is checked, except
`MODELLED`. Standard library only.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec"

#: The clinical tables this platform models. Vocabulary tables are read from the user's ATHENA
#: download (`clinicalomx_omop.athena`) instead.
MODELLED = (
    "person",
    "visit_occurrence",
    "condition_occurrence",
    "procedure_occurrence",
    "drug_exposure",
    "measurement",
    "observation",
    "death",
    "specimen",
)


def _spec_file(source: dict, key: str) -> Path:
    entry = source["files"][key]
    path = SPEC / entry["name"]
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != entry["sha256"]:
        sys.exit(f"{path.name}: sha256 {digest} does not match spec/source.toml "
                 f"({entry['sha256']}). Refetch it at commit {source['commit']}, or record the "
                 "new file's digest there as part of a deliberate CDM bump.")
    return path


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def _na(value: str) -> str | None:
    return None if value in ("", "NA") else value


def _true(value: str) -> bool:
    return value.strip().lower() == "true"


def render(source: dict) -> str:
    tables = {r["cdmTableName"]: r for r in _rows(_spec_file(source, "table_level"))}
    fields = _rows(_spec_file(source, "field_level"))
    missing = [t for t in MODELLED if t not in tables]
    if missing:
        sys.exit(f"MODELLED names tables the specification does not have: {missing}")

    out = [
        f'"""OMOP CDM v{source["cdm_version"]}, the tables this platform models.',
        "",
        "GENERATED by scripts/generate_cdm.py. Do not edit: change the specification or the",
        "generator and regenerate, so the diff is the change.",
        "",
        f"Source: {source['repository']} at {source['tag']} ({source['commit']}),",
        f"{source['files']['field_level']['name']} and {source['files']['table_level']['name']}.",
        '"""',
        "",
        "from . import Field, Release, Table",
        "",
        "RELEASE = Release(",
        f"    version={source['cdm_version']!r},",
        f"    tag={source['tag']!r},",
        f"    commit={source['commit']!r},",
        "    tables=(",
    ]
    for name in (t for t in tables if t in MODELLED):
        out += [
            "        Table(",
            f"            name={name!r},",
            f"            description={tables[name]['tableDescription']!r},",
            "            fields=(",
        ]
        for row in (r for r in fields if r["cdmTableName"] == name):
            fk_table = _na(row["fkTableName"])
            out.append(
                f"                Field({row['cdmFieldName']!r}, {row['cdmDatatype']!r}, "
                f"required={_true(row['isRequired'])}, "
                f"primary_key={_true(row['isPrimaryKey'])}, "
                f"fk_table={fk_table.lower() if fk_table else None!r}, "
                f"fk_domain={_na(row['fkDomain'])!r}, "
                f"description={row['userGuidance'] if _na(row['userGuidance']) else ''!r}),"
            )
        out += ["            ),", "        ),"]
    out += ["    ),", ")", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed module differs from a fresh render")
    args = parser.parse_args()

    source = tomllib.loads((SPEC / "source.toml").read_text())
    target = (ROOT / "src" / "clinicalomx_omop" / "cdm"
              / f"v{source['cdm_version'].replace('.', '_')}.py")
    rendered = render(source)
    if args.check:
        if not target.exists() or target.read_text() != rendered:
            sys.exit(f"{target.relative_to(ROOT)} is stale: run scripts/generate_cdm.py")
        return
    target.write_text(rendered)
    print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
