"""The OMOP CDM as data: one `Release` per CDM version.

`v5_4.py` is generated by `scripts/generate_cdm.py` from the OHDSI specification and committed.
"""

from __future__ import annotations

import datetime
from dataclasses import dataclass

#: `cdmDatatype` (lowercased) -> lamindb feature dtype. `varchar(n)` is any string. An
#: unmapped datatype raises in `Field.dtype`.
_DTYPES: dict[str, type] = {
    "integer": int,
    "bigint": int,
    "float": float,
    "date": datetime.date,
    "datetime": datetime.datetime,
}


@dataclass(frozen=True)
class Field:
    """One CDM field, as the field-level specification states it."""

    name: str
    #: `cdmDatatype`, verbatim.
    datatype: str
    required: bool
    primary_key: bool = False
    #: `fkTableName`, lowercased, when the field references another table; `concept` for concept
    #: identifiers.
    fk_table: str | None = None
    #: `fkDomain`: the OMOP domain a concept-valued field's concept must be in.
    fk_domain: str | None = None
    #: `userGuidance`.
    description: str = ""

    @property
    def dtype(self) -> type:
        """The lamindb dtype for this field. Raises on an unmapped datatype."""
        key = self.datatype.lower()
        if key.startswith("varchar"):
            return str
        try:
            return _DTYPES[key]
        except KeyError:
            raise ValueError(f"no lamindb dtype for CDM datatype {self.datatype!r} "
                             f"({self.name}); add it to cdm._DTYPES") from None


@dataclass(frozen=True)
class Table:
    """One CDM table: name, description, and fields in specification order."""

    name: str
    description: str
    fields: tuple[Field, ...]

    def field(self, name: str) -> Field:
        return next(f for f in self.fields if f.name == name)


@dataclass(frozen=True)
class Release:
    """One CDM version, with the upstream commit its specification was read at."""

    version: str
    tag: str
    commit: str
    tables: tuple[Table, ...]

    @property
    def name(self) -> str:
        """The release's lamindb name, used for its Record, Feature and Schema types.

        The CDM version is in the name; each release is a separate set of types.
        """
        return f"OMOP_CDM_v{self.version}"

    def type_name(self, table: str) -> str:
        """The Record type, Feature type and Schema name for one table of this release."""
        return f"{self.name}.{table}"

    def table(self, name: str) -> Table:
        return next(t for t in self.tables if t.name == name)


