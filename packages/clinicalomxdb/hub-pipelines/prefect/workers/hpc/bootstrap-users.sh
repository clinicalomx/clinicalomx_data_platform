#!/usr/bin/env bash
# Provision the per-user half of the HPC socket broker, from users.conf.
#
# For every user in users.conf this writes an ssh_config alias, registers a Prefect SSH block
# and a work pool, and installs a templated worker unit. The login terminal that establishes
# each socket is the other half, in hub-ops/ttyd.
#
# Why per user at all: HPC submission goes through a DUO-authenticated ControlMaster socket,
# and a socket belongs to exactly one HPC account. One worker equals one user equals one
# socket equals one allocation, so choosing a work pool is how a deployment chooses whose
# allocation it runs under. A service account with key authentication would have removed the
# need for any of this; that was checked with the facility and is not possible.
#
# Idempotent and re-runnable. Safe to run after editing users.conf: aliases and units for
# users that have been REMOVED are stopped and disabled.
#
# What it deliberately does NOT do: kill or re-authenticate a live socket. Sockets are
# established by a human completing DUO and persist across runs of this script.
#
# Run from anywhere; re-execs itself with sudo.
#
# Site values come from site.env at the repository root (scripts/site/render.py): the login host,
# and the work pool's SLURM defaults deploy.py writes into each new pool. users.conf beside this
# script is rendered from the same site.yaml.
#
# Overridable environment:
#   HPC_LOGIN_HOST   HPC login host (default: hpc.login_host from site.env)
#   PREFECT_API_URL    Prefect API (default http://localhost:4200/api)
#   USERS_FILE         alternative users.conf path
set -euo pipefail

# The script's own location, with symlinks LEFT ALONE. readlink -f, which this used, names the
# physical /opt/<root>/releases/<tag> path, so the per-user units it rendered pinned one release
# tree and the next `ln -sfn releases/<tag> current` left them running a tree that is about to be
# removed. infra/systemd/hpc-ssh-pool-worker@.service is the tracked render of this same
# template and names the current/ path; a logical path here makes the two agree.
SELF_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
SELF="$SELF_DIR/$(basename -- "${BASH_SOURCE[0]}")"

case "$SELF" in
    */releases/platform-v*) echo "WARNING: rendering from a release tree directly, so the units" \
        "below cannot survive the next current/ flip. Re-run from the current/ path." >&2 ;;
esac

if [ "$(id -u)" -ne 0 ]; then
    exec sudo \
        HPC_LOGIN_HOST="${HPC_LOGIN_HOST:-}" \
        PREFECT_API_URL="${PREFECT_API_URL:-}" \
        USERS_FILE="${USERS_FILE:-}" \
        bash "$SELF" "$@"
fi

SCRIPT_DIR="$(dirname "$SELF")"
PREFECT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
VENV="$PREFECT_DIR/.venv"
SITE_ENV="$(cd "$SCRIPT_DIR/../../../../../.." && pwd)/site.env"
[ -f "$SITE_ENV" ] || { echo "ERROR: $SITE_ENV missing; render it: uv run scripts/site/render.py" >&2; exit 1; }
set -a; . "$SITE_ENV"; set +a
# deploy.py runs through `sudo -u`, which drops the environment, so the site values are passed to
# it by name. render.py refuses whitespace in a value, which is what makes the word split safe.
SITE_VARS="$(grep -E '^[A-Z][A-Z0-9_]*=' "$SITE_ENV")"
USERS_FILE="${USERS_FILE:-$SCRIPT_DIR/users.conf}"
HPC_LOGIN_HOST="${HPC_LOGIN_HOST:-$CLINICALOMX_SITE_HPC_LOGIN_HOST}"
PREFECT_API_URL="${PREFECT_API_URL:-http://localhost:4200/api}"
UNIT_TEMPLATE="$SCRIPT_DIR/hpc-ssh-pool-worker@.service"
UNIT_NAME="hpc-ssh-pool-worker@.service"
# The deployed destination is the default. The override exists so
# tests/explorer/test_ops_bootstrap_paths.py can run this script whole as an ordinary user.
SYSTEMD_DIR="${SYSTEMD_DIR:-/etc/systemd/system}"

# The worker account owns the checkout, the ssh config and every ControlMaster socket.
RUN_USER="$(stat -c '%U' "$PREFECT_DIR")"
RUN_HOME="$(getent passwd "$RUN_USER" | cut -d: -f6)"
SSH_CONFIG="$RUN_HOME/.ssh/config"

# Managed region markers. Everything outside them in ~/.ssh/config is preserved, so an
# operator's own entries survive a re-run.
BEGIN_MARK="# >>> clinicalomxdb hpc users (generated by bootstrap-users.sh) >>>"
END_MARK="# <<< clinicalomxdb hpc users <<<"

log() { echo "[users] $*"; }

[ -f "$USERS_FILE" ] || { echo "ERROR: users file not found: $USERS_FILE" >&2; exit 1; }
[ -f "$UNIT_TEMPLATE" ] || { echo "ERROR: unit template not found: $UNIT_TEMPLATE" >&2; exit 1; }

# Strip comments and blanks. Order is significant: the first entry is the primary user.
mapfile -t USERS < <(sed -e 's/#.*//' -e 's/[[:space:]]//g' "$USERS_FILE" | grep -v '^$')
[ "${#USERS[@]}" -gt 0 ] || { echo "ERROR: no users in $USERS_FILE" >&2; exit 1; }
PRIMARY="${USERS[0]}"
log "users: ${USERS[*]} (primary: $PRIMARY)"

# --- 1. ssh_config aliases -------------------------------------------------------------
# One entry per user. The primary additionally answers to the bare `hpc`, because the docs,
# the manual DUO step and the original Prefect block all use that name.
#
# ControlPath's %r token expands to the remote user and %h to the RESOLVED hostname, so each
# user gets a distinct socket for free while the two names of the primary share one. That is
# what lets the alias be added without invalidating a live DUO session.
GENERATED="$(
    printf '%s\n' "$BEGIN_MARK"
    for user in "${USERS[@]}"; do
        if [ "$user" = "$PRIMARY" ]; then
            printf 'Host hpc hpc-%s\n' "$user"
        else
            printf 'Host hpc-%s\n' "$user"
        fi
        printf '    HostName %s\n' "$HPC_LOGIN_HOST"
        printf '    User %s\n' "$user"
        printf '    ControlMaster auto\n'
        printf '    ControlPath ~/.ssh/cm-%%r@%%h:%%p\n'
        printf '    ControlPersist 96h\n'
        printf '    ServerAliveInterval 60\n'
        printf '    ServerAliveCountMax 3\n'
    done
    printf '%s\n' "$END_MARK"
)"

mkdir -p "$RUN_HOME/.ssh"
touch "$SSH_CONFIG"
GENERATED="$GENERATED" BEGIN_MARK="$BEGIN_MARK" END_MARK="$END_MARK" \
python3 - "$SSH_CONFIG" <<'PY'
import os, sys

path = sys.argv[1]
begin, end = os.environ["BEGIN_MARK"], os.environ["END_MARK"]
block = os.environ["GENERATED"].rstrip("\n") + "\n"

lines = open(path).read().splitlines(keepends=True)
out, inside, replaced = [], False, False
for line in lines:
    if line.strip() == begin:
        inside = True
        out.append(block)
        replaced = True
        continue
    if inside:
        if line.strip() == end:
            inside = False
        continue
    out.append(line)

if not replaced:
    if out and not out[-1].endswith("\n"):
        out.append("\n")
    out.append(block)

open(path, "w").write("".join(out))
print("[users] ssh config %s" % ("managed block replaced" if replaced else "managed block appended"))
PY

chown -R "$RUN_USER:$RUN_USER" "$RUN_HOME/.ssh"
chmod 700 "$RUN_HOME/.ssh"
chmod 600 "$SSH_CONFIG"

# Prove every alias parses and resolves to the intended account before anything depends on it.
for user in "${USERS[@]}"; do
    resolved="$(sudo -u "$RUN_USER" ssh -G "hpc-$user" 2>/dev/null | awk '/^user /{print $2}')"
    if [ "$resolved" != "$user" ]; then
        echo "ERROR: alias hpc-$user resolves to user '$resolved', expected '$user'" >&2
        exit 1
    fi
    log "alias hpc-$user -> $user OK"
done

# --- 2. Prefect blocks + work pools ----------------------------------------------------
if [ -x "$VENV/bin/python" ]; then
    for user in "${USERS[@]}"; do
        log "registering block + pool for $user"
        # shellcheck disable=SC2086
        sudo -u "$RUN_USER" env $SITE_VARS \
            PREFECT_API_URL="$PREFECT_API_URL" \
            HPC_USER="$user" \
            "$VENV/bin/python" "$SCRIPT_DIR/deploy.py"
    done
else
    log "WARNING: no venv at $VENV, skipping block/pool registration"
    log "         run workers/hpc/bootstrap.sh first, then re-run this script"
fi

# --- 3. templated worker units ---------------------------------------------------------
# One instance per user, each polling that user's pool through that user's block. worker.py
# needs no change: it already reads the block name from HPC_SSH_BLOCK.
log "installing $UNIT_NAME"
# What each RUNNING instance executes, read before the render overwrites the template. Rendering
# does not touch a live worker: `enable --now` starts a stopped instance and leaves a running one
# alone, so this is the last moment an instance still running a previous release can be spotted.
declare -A PREV_EXEC=()
for user in "${USERS[@]}"; do
    inst="hpc-ssh-pool-worker@$user.service"
    if [ "$(systemctl is-active "$inst" 2>/dev/null || true)" = "active" ]; then
        PREV_EXEC[$user]="$(systemctl show -p ExecStart --value "$inst" 2>/dev/null || true)"
    fi
done

rm -f "$SYSTEMD_DIR/$UNIT_NAME"
sed -e "s#@PREFECT_DIR@#$PREFECT_DIR#g" \
    -e "s#@SITE_ENV@#$SITE_ENV#g" \
    -e "s#@RUN_USER@#$RUN_USER#g" \
    -e "s#@RUN_HOME@#$RUN_HOME#g" \
    "$UNIT_TEMPLATE" > "$SYSTEMD_DIR/$UNIT_NAME"
systemctl daemon-reload

for user in "${USERS[@]}"; do
    systemctl enable --now "hpc-ssh-pool-worker@$user.service"
    log "started hpc-ssh-pool-worker@$user"
done

# An instance that was already up is still submitting through the venv of the tree it started
# from. Restarting it here would kill an in-flight submission with no drain, which is an operator
# step behind approval gate 10, so this only reports it.
for user in "${USERS[@]}"; do
    case "${PREV_EXEC[$user]:-}" in
        ""|*"$PREFECT_DIR"*) ;;
        *) log "RESTART NEEDED: hpc-ssh-pool-worker@$user still runs ${PREV_EXEC[$user]}"
           log "                drain first, then: systemctl restart hpc-ssh-pool-worker@$user" ;;
    esac
done

# Retire instances for users no longer listed. Their sockets are left alone; only the worker
# that would poll on their behalf is stopped.
for unit in $(systemctl list-units --all --plain --no-legend 'hpc-ssh-pool-worker@*' \
              | awk '{print $1}'); do
    instance="${unit#hpc-ssh-pool-worker@}"
    instance="${instance%.service}"
    keep=0
    for user in "${USERS[@]}"; do [ "$user" = "$instance" ] && keep=1; done
    if [ "$keep" -eq 0 ]; then
        log "retiring $unit (no longer in users.conf)"
        systemctl disable --now "$unit" || true
    fi
done

log "done. Per-user state:"
for user in "${USERS[@]}"; do
    alive=$(sudo -u "$RUN_USER" ssh -O check "hpc-$user" 2>&1 || true)
    printf '[users]   %-12s worker=%s socket=%s\n' \
        "$user" \
        "$(systemctl is-active "hpc-ssh-pool-worker@$user.service")" \
        "$(case "$alive" in *"Master running"*) echo alive ;; *) echo DEAD ;; esac)"
done
log "a DEAD socket is expected until that user completes DUO once at /ssh/USER/ on the portal"
