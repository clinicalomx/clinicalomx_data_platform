"""Render the vocabulary reference from ``data/`` and ``names.py``.

    python -m clinicalomx.vocab docs > docs/reference.md      # regenerate
    python -m clinicalomx.vocab docs --check docs/reference.md # CI gate

Foundation only and deterministic; consumer ownership is ``audit``'s job. Needs no database.
"""

from __future__ import annotations

from ..names import FEATURES, TYPES

_HEADER = """\
# clinicalomx vocabulary reference

GENERATED by `python -m clinicalomx.vocab docs`. Do not edit by hand - edit `data/` or
`names.py` and regenerate, or CI will fail.

clinicalomx {version} | declared vocabulary `{digest}`

The **foundation**: what the framework itself reads or writes, plus the interchange
conventions no single repo owns. It is a contract, not an inventory of the instance -
features beyond it are expected and are declared by the repo that uses them. See
`docs/migration.md` for the ownership map.
"""


def _constant_index() -> dict[str, str]:
    """``{feature value: "FEATURES.NAME"}``."""
    out = {}
    for cls, label in ((TYPES, "TYPES"), (FEATURES, "FEATURES")):
        for attr, value in vars(cls).items():
            if not attr.startswith("_") and isinstance(value, str):
                out[f"{label}:{value}"] = f"{label}.{attr}"
    return out


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["_none declared_", ""]
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(c.replace("|", "\\|") or "" for c in r) + " |" for r in rows]
    return out + [""]


def render() -> str:
    """The reference, as markdown. Pure: same inputs, same bytes."""
    from . import dataio, ledger

    const = _constant_index()
    lines = [_HEADER.format(version=_version(), digest=ledger.content_hash())]

    types = sorted(dataio.types(), key=lambda t: t["name"].lower())
    rows = [[t["name"], t.get("type", ""), const.get(f"TYPES:{t['name']}", ""),
             t.get("description", "")] for t in types]
    # Types created at apply time rather than declared in types.yaml, such as SeedVersion.
    declared = {t["name"] for t in types}
    # Skip dunders: vars() also yields __module__ and __doc__.
    runtime = sorted(v for k, v in vars(TYPES).items()
                     if not k.startswith('_') and isinstance(v, str) and v not in declared)
    rows += [[n, "", const.get(f"TYPES:{n}", ""), "_created at apply time_"]
             for n in runtime]
    lines += [f"## Types ({len(rows)})", ""]
    lines += _table(["name", "parent", "constant", "description"], rows)

    feats = sorted(dataio.features(), key=lambda r: r["name"].lower())
    active = [f for f in feats if (f.get("status") or "active").strip() == "active"]
    lines += [f"## Features ({len(active)} active, {len(feats) - len(active)} deprecated)", ""]
    lines += _table(
        ["name", "dtype", "constant", "status", "description"],
        [[f["name"], f"`{f['dtype']}`", const.get(f"FEATURES:{f['name']}", ""),
          (f.get("status") or "active").strip(), f.get("description", "")] for f in feats],
    )

    st = dataio.storages(expand=False)
    lines += [f"## Storages ({len(st)})", ""]
    lines += _table(
        ["key", "root", "host", "description"],
        [[s["key"], f"`{s['root']}`", s.get("host", ""), s.get("description", "")] for s in st],
    )

    srcs = (dataio.sources_lock().get("sources") or {})
    lines += ["## Pinned ontologies", ""]
    lines += _table(
        ["entity", "source", "version", "organism"],
        [[e, v.get("source", ""), f"`{v.get('version', '')}`", v.get("organism", "")]
         for e, v in sorted(srcs.items())],
    )

    return "\n".join(lines).rstrip() + "\n"


def _version() -> str:
    from .. import __version__

    return __version__
