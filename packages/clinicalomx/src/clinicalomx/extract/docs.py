"""Render the extract reference from :mod:`clinicalomx.extract.recipes`.

    python -m clinicalomx.extract docs > docs/extract-recipes.md          # regenerate
    python -m clinicalomx.extract docs --check docs/extract-recipes.md    # CI gate

Foundation recipes only, and deterministic; ``clinicalomx-extract recipes`` shows installed ones.
Needs no database.
"""
from __future__ import annotations

from clinicalomx.extract.builders.kinds import RULES

_HEADER = """\
# clinicalomx extract reference

GENERATED by `python -m clinicalomx.extract docs`. Do not edit by hand - edit
`src/clinicalomx/extract/recipes.py` and regenerate, or CI will fail.

clinicalomx {version}

A **recipe** is one named downstream product you can ask an ROI for. `plan` resolves a recipe
against what is actually registered and tells you what you would get; `assemble` builds it.

Reading the tables below:

- **roles** are candidates in PREFERENCE ORDER, best first. The planner takes the first one that
  is present, so `bgnormed, source_image` means "the normalised crop if it exists, else derive it
  from the whole-slide image".
- an **optional** element that resolves absent is omitted and the object still builds; a
  **required** one that resolves absent blocks the plan; **one of** means the recipe needs at
  least one of that group, and takes whichever are there.
- a **variable** names one array inside a multi-variable artifact. The background-normalised zarr
  holds several, so two elements can read the same role and get different images.
- **needs** are ROI-side features that must carry a value for the element to be placeable. They
  are presence-checked only; what they mean belongs to the recipe's placement.
- a role no installed consumer declares is not a fault. It resolves absent today and the same
  recipe upgrades itself once something registers that role.
"""


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["_none declared_", ""]
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(c.replace("|", "\\|") or "" for c in r) + " |" for r in rows]
    return out + [""]


def _code_list(values) -> str:
    return ", ".join(f"`{v}`" for v in values)


def render() -> str:
    """The reference, as markdown. Pure: same inputs, same bytes."""
    from clinicalomx.extract.recipes import FOUNDATION_RECIPES

    recipes = sorted(FOUNDATION_RECIPES, key=lambda r: r.name)
    lines = [_HEADER.format(version=_version())]

    lines += [f"## Recipes ({len(recipes)})", ""]
    lines += _table(
        ["recipe", "target", "asked of", "layout", "elements", "registers as"],
        [[f"`{r.name}`", r.target, _code_list(r.roi_types), f"`{r.layout}`",
          str(len(r.elements)), f"`{r.publish_role}`" if r.publish_role else "_local only_"]
         for r in recipes],
    )

    lines += ["## Layouts", ""]
    lines += _table(
        ["layout", "produces"],
        [["`single`", "one object for the ROI you asked about"],
         ["`merged`",
          "ONE object for the ROI, with an element per child, in one coordinate system"],
         ["`per_child`", "one object PER child of the ROI you asked about"]],
    )

    for r in recipes:
        lines += [f"## `{r.name}`", ""]
        if r.description:
            lines += [r.description, ""]
        required_for = set(r.requires_any)
        lines += _table(
            ["element", "kind", "roles (in preference order)", "variable", "required",
             "read from", "needs"],
            [[f"`{e.name}`", e.kind, _code_list(e.roles),
              f"`{e.variable}`" if e.variable else "",
              "yes" if e.required else ("one of" if e.name in required_for else "no"),
              f"`{e.level}`", _code_list(e.needs_features)]
             for e in r.elements],
        )
        if r.requires_any:
            lines += [f"At least one of {_code_list(r.requires_any)} must be present; whichever "
                      f"are become the output's series. All of them absent blocks the plan rather "
                      f"than writing an empty file.", ""]
        lines += [f"Coordinate space `{r.coordinate_space}`. "
                  f"Builder `{r.builder}`, placement `{r.placement}`.", ""]

    lines += ["## Element kinds", ""]
    lines += [
        "Which slot an artifact belongs in. A recipe declares its element's kind explicitly; this",
        "is the rule that says what it SHOULD be, and `extract.element_kind_matches_the_artifact`",
        "reports a disagreement. It is why a new artefact usually needs a row in an existing",
        "recipe rather than a product of its own - the per-core bgnorm QC parquet is a `table`",
        "because it has no geometry column, and that is the whole decision.",
        "",
    ]
    lines += _table(["the artifact is", "the element kind is"],
                    [[desc, f"`{kind}`"] for desc, kind in RULES])

    roles = sorted({role for r in recipes for e in r.elements for role in e.roles})
    lines += ["## Every role this catalogue can read", ""]
    lines += [
        "Whether a role is *declared* depends on which consumer distributions are installed here;",
        "whether it is *populated* depends on the instance. Ask `clinicalomx-extract describe`.",
        "",
    ]
    lines += _table(
        ["role", "used by"],
        [[f"`{role}`", _code_list(r.name for r in recipes
                                  if any(role in e.roles for e in r.elements))]
         for role in roles],
    )

    return "\n".join(lines).rstrip() + "\n"


def _version() -> str:
    from clinicalomx import __version__

    return __version__
